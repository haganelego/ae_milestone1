"""ROBOVIS2027 recovery plan §6.2 (Phase D) helpers for the frozen 60-image test set.

Subcommands:
  prepare   384-base 20-level degradation of the 60 ids in <rec>/test_selection.json with
            scripts/27's process_image and the configs/robovis2027.yaml settings (new ids
            only, refuses existing dirs), written to the usual degraded_images/<id>/;
            the manifest goes to <rec>/levels_manifest_test_rec.json (the existing
            levels_manifest.json is untouched). Also writes <rec>/selected_images_test_rec.json
            (split "test", rank = selection order) and configs/robovis2027_test_rec.yaml
            (robovis2027.yaml with only those two paths replaced) so scripts/25, 35 and 28
            run unchanged with --config.
  metrics   scripts/28 scoring of one PGSG graph dir of outputs/robovis2027/test_rec,
            restricted to --levels, saved as <rec>/stage_metrics_<name>.csv (+ seed column).

Usage:
  uv run --project egtr python scripts/46_recovery_test_rec.py prepare
  uv run --project egtr python scripts/46_recovery_test_rec.py metrics --graphs-subdir graphs --name seedA --seed-label A
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd
import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from milestone1.config import resolve  # noqa: E402
from milestone1.robovis_data import (  # noqa: E402
    RESAMPLE_FILTERS,
    load_robovis_config,
    sha256_file,
)

REC_DIR = REPO_ROOT / "outputs/robovis2027_recovery/rec_r0"
RUN_ID = "test_rec"
SPLIT = "test"
BASE_CONFIG = REPO_ROOT / "configs/robovis2027.yaml"
TEST_CONFIG = REPO_ROOT / "configs/robovis2027_test_rec.yaml"
SELECTED_NAME = "selected_images_test_rec.json"
LEVELS_NAME = "levels_manifest_test_rec.json"


def _load_script(name: str, filename: str):  # noqa: ANN202 (module object)
    spec = importlib.util.spec_from_file_location(
        name, REPO_ROOT / "scripts" / filename
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def prepare() -> None:
    s27 = _load_script("s27", "27_robovis_generate_levels.py")
    cfg = load_robovis_config(BASE_CONFIG)
    ds, res, paths = cfg["dataset"], cfg["resolution"], cfg["paths"]
    selection = json.loads((REC_DIR / "test_selection.json").read_text())
    ids = [int(i) for i in selection["selected_ids"]]
    out_root = resolve(paths["degraded_images"])
    s27.check_output_root(out_root)
    clash = [i for i in ids if (out_root / str(i)).exists()]
    if clash:
        raise RuntimeError(
            f"degraded dirs already exist for {clash[:5]} (refusing to overwrite)"
        )
    records = [
        {"image_id": i, "split": SPLIT, "rank": r, "file_name": f"{i}.jpg"}
        for r, i in enumerate(ids)
    ]
    scales = [float(s) for s in res["scales"]]
    entries = [
        s27.process_image(
            rec,
            Path(ds["vg_root"]) / "images",
            out_root,
            scales,
            int(ds["base_max_side"]),
            RESAMPLE_FILTERS[res["interpolation"]],
            int(res["jpeg_quality"]),
            res["output_format"],
        )
        for rec in records
    ]
    (REC_DIR / SELECTED_NAME).write_text(json.dumps(records, indent=1))
    manifest = {
        "script": "scripts/46_recovery_test_rec.py prepare (scripts/27 process_image)",
        "created": datetime.now().isoformat(timespec="seconds"),
        "selection": "rec_r0/test_selection.json selected_ids (order = rank)",
        "base_max_side": int(ds["base_max_side"]),
        "scales": scales,
        "interpolation": res["interpolation"],
        "output_format": res["output_format"],
        "jpeg_quality": int(res["jpeg_quality"]),
        "output_root": paths["degraded_images"],
        "images": entries,
    }
    (REC_DIR / LEVELS_NAME).write_text(json.dumps(manifest, indent=1))
    raw = yaml.safe_load(BASE_CONFIG.read_text())
    raw["paths"]["selected_images"] = str(
        (REC_DIR / SELECTED_NAME).relative_to(REPO_ROOT)
    )
    raw["paths"]["levels_manifest"] = str(
        (REC_DIR / LEVELS_NAME).relative_to(REPO_ROOT)
    )
    header = (
        f"# GENERATED by scripts/46_recovery_test_rec.py from configs/robovis2027.yaml "
        f"(sha256 {sha256_file(BASE_CONFIG)}); only paths.selected_images and paths.levels_manifest differ.\n"
    )
    TEST_CONFIG.write_text(header + yaml.safe_dump(raw, sort_keys=False))
    print(
        f"prepared {len(entries)} images x {len(scales)} levels; config {TEST_CONFIG.relative_to(REPO_ROOT)}"
    )


def metrics(graphs_subdir: str, name: str, seed_label: str, levels: list[int]) -> None:
    s28 = _load_script("s28", "28_robovis_stage_metrics.py")
    cfg = load_robovis_config(TEST_CONFIG)
    run_dir = resolve(cfg["output_root"]) / RUN_ID
    rows = s28.compute(run_dir, cfg, graphs_subdir)[0]
    stage = pd.DataFrame(rows)
    stage = stage[stage.t.isin(levels)].copy()
    stage.insert(0, "seed", seed_label)
    out = REC_DIR / f"stage_metrics_{name}.csv"
    stage.to_csv(out, index=False)
    print(
        f"{out.relative_to(REPO_ROOT)}: {len(stage)} rows, valid {int(pd.to_numeric(stage.valid).sum())}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("prepare")
    m = sub.add_parser("metrics")
    m.add_argument("--graphs-subdir", required=True)
    m.add_argument("--name", required=True)
    m.add_argument("--seed-label", required=True)
    m.add_argument("--levels", default=",".join(str(t) for t in range(1, 21)))
    args = parser.parse_args()
    if args.cmd == "prepare":
        prepare()
    else:
        metrics(
            args.graphs_subdir,
            args.name,
            args.seed_label,
            [int(x) for x in args.levels.split(",")],
        )


if __name__ == "__main__":
    main()
